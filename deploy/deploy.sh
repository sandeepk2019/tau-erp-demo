#!/usr/bin/env bash
# ============================================================================
# Tau ERP — One-Command Production Deployment for Ubuntu 22.04 / 24.04 VPS
# (tested against Hostinger KVM plans, works on any Ubuntu/Debian VPS)
#
# Usage:
#   sudo bash deploy/deploy.sh                      # no domain → http://SERVER_IP
#   sudo bash deploy/deploy.sh erp.yourdomain.com   # with domain → https:// (auto-SSL)
#
# What it does:
#   1. Installs system deps, Bun runtime, Caddy web server, enables firewall
#   2. Installs the app to /opt/tau-erp under a dedicated non-root user
#   3. Builds the Next.js standalone bundle and seeds the SQLite DB if empty
#   4. Creates a systemd service (auto-restart, auto-start on reboot)
#   5. Configures Caddy reverse proxy with automatic HTTPS (Let's Encrypt)
#   6. Runs a health check and prints access URLs
#
# Safe to re-run (idempotent): re-deploys code, keeps existing .env and DB.
# ============================================================================
set -euo pipefail

# ----------------------------- configuration --------------------------------
APP_NAME="tau-erp"
INSTALL_DIR="/opt/tau-erp"
SERVICE_USER="tau"
APP_PORT=3000
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # project root (where this repo lives)

# ----------------------------- pretty output --------------------------------
GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
step()  { echo -e "\n${CYAN}▶${NC} ${BOLD}$1${NC}"; }
ok()    { echo -e "  ${GREEN}✔${NC} $1"; }
warn()  { echo -e "  ${YELLOW}⚠${NC} $1"; }
fail()  { echo -e "  ${RED}✖ $1${NC}"; exit 1; }

# ----------------------------- preflight ------------------------------------
step "Preflight checks"
[[ $EUID -eq 0 ]] || fail "Run as root:  sudo bash deploy/deploy.sh"
. /etc/os-release
ok "OS: ${PRETTY_NAME:-unknown}"
[[ -f "$SRC_DIR/package.json" ]] || fail "Run this script from inside the Tau ERP project (package.json not found next to deploy/)"
ok "Source project: $SRC_DIR"

DOMAIN="${1:-}"
if [[ -z "$DOMAIN" ]]; then
  read -r -p "Enter your domain (e.g. erp.yourcompany.com) — press Enter to skip and use http://SERVER_IP: " DOMAIN || true
fi
if [[ -n "$DOMAIN" ]]; then
  ok "Target: https://$DOMAIN (SSL auto-issued by Caddy after DNS propagates)"
else
  warn "No domain given — site will be served at http://<SERVER_IP> (no SSL)"
fi

# ----------------------------- 1. system deps -------------------------------
step "1/8 Installing system dependencies (curl, rsync, ufw, openssl, cron)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq curl rsync ufw openssl cron ca-certificates gnupg dnsutils >/dev/null
ok "System dependencies installed"

# ----------------------------- 2. bun runtime -------------------------------
step "2/8 Installing Bun runtime"
if [[ -x /usr/local/bin/bun ]]; then
  ok "Bun already present: $(/usr/local/bin/bun --version)"
else
  curl -fsSL https://bun.sh/install | BUN_INSTALL="/root/.bun" bash >/dev/null
  ln -sf /root/.bun/bin/bun /usr/local/bin/bun
  ln -sf /root/.bun/bin/bunx /usr/local/bin/bunx 2>/dev/null || true
  ok "Bun $(/usr/local/bin/bun --version) installed globally"
fi

# ----------------------------- 3. swap insurance (small VPS) ----------------
step "3/8 Memory guard (swap if VPS has < 4 GB RAM)"
TOTAL_MEM_KB=$(awk '/MemTotal/ {print $2}' /proc/meminfo)
TOTAL_SWAP_KB=$(awk '/SwapTotal/ {print $2}' /proc/meminfo)
if (( TOTAL_MEM_KB + TOTAL_SWAP_KB < 3600000 )) && [[ ! -f /swapfile ]]; then
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  ok "2 GB swapfile created (protects the production build from OOM)"
else
  ok "Enough memory present — no swap needed"
fi

# ----------------------------- 4. install app files -------------------------
step "4/8 Installing app to $INSTALL_DIR (dedicated non-root user)"
id -u "$SERVICE_USER" &>/dev/null || useradd --system --create-home --shell /bin/bash "$SERVICE_USER"
mkdir -p "$INSTALL_DIR"
rsync -a --delete \
  --exclude node_modules --exclude .next --exclude .git \
  --exclude dev.log --exclude server.log --exclude '*.log' \
  "$SRC_DIR"/ "$INSTALL_DIR"/
ok "Code synced to $INSTALL_DIR"

ENV_FILE="$INSTALL_DIR/.env"
if [[ -f "$ENV_FILE" ]]; then
  ok "Existing .env preserved (secrets kept)"
else
  NEXTAUTH_SECRET_VALUE="$(openssl rand -base64 32)"
  if [[ -n "$DOMAIN" ]]; then
    PUBLIC_URL="https://$DOMAIN"
  else
    SERVER_IP=$(curl -fs4 ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')
    PUBLIC_URL="http://$SERVER_IP"
  fi
  cat > "$ENV_FILE" <<EOF
# Tau ERP production environment (generated by deploy.sh)
DATABASE_URL=file:$INSTALL_DIR/db/custom.db
NEXTAUTH_URL=$PUBLIC_URL
NEXTAUTH_SECRET=$NEXTAUTH_SECRET_VALUE
NODE_ENV=production
EOF
  chmod 600 "$ENV_FILE"
  ok ".env created (NEXTAUTH_SECRET generated, NEXTAUTH_URL=$PUBLIC_URL)"
fi
chown -R "$SERVICE_USER:$SERVICE_USER" "$INSTALL_DIR"
mkdir -p "$INSTALL_DIR/db" && chown "$SERVICE_USER:$SERVICE_USER" "$INSTALL_DIR/db"

# ----------------------------- 5. build --------------------------------------
step "5/8 Installing dependencies & building production bundle (2–4 min)"
sudo -u "$SERVICE_USER" -H bash -lc "
  set -e
  cd $INSTALL_DIR
  export NODE_OPTIONS=--max-old-space-size=2048
  bun install --frozen-lockfile 2>/dev/null || bun install
  bunx prisma generate
  bun run build:standalone
  if [[ ! -f $INSTALL_DIR/db/custom.db ]]; then
    bunx prisma db push --accept-data-loss
    bun scripts/seed-runner.ts || true
  fi
"
[[ -f "$INSTALL_DIR/.next/standalone/server.js" ]] || fail "Build failed — standalone server.js not found. Check output above."
ok "Build complete — standalone bundle ready"

# ----------------------------- 6. systemd service ---------------------------
step "6/8 Creating systemd service (auto-restart + start on boot)"
sed -e "s|__INSTALL_DIR__|$INSTALL_DIR|g" "$INSTALL_DIR/deploy/tau-erp.service" > /etc/systemd/system/${APP_NAME}.service
systemctl daemon-reload
systemctl enable ${APP_NAME} >/dev/null 2>&1
systemctl restart ${APP_NAME}
ok "Service 'tau-erp' running (TZ=Asia/Kolkata, port $APP_PORT bound to localhost)"

# ----------------------------- 7. firewall + reverse proxy ------------------
step "7/8 Firewall + Caddy reverse proxy (automatic HTTPS)"
ufw allow OpenSSH  >/dev/null 2>&1 || true
ufw allow 80/tcp   >/dev/null 2>&1 || true
ufw allow 443/tcp  >/dev/null 2>&1 || true
ufw --force enable >/dev/null 2>&1 || true
ok "Firewall: only SSH(22), HTTP(80), HTTPS(443) open"

apt-get install -y -qq debian-keyring debian-archive-keyring apt-transport-https >/dev/null
curl -fsSL 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --batch --yes --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg 2>/dev/null || true
curl -fsSL 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' | tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
apt-get update -qq && apt-get install -y -qq caddy >/dev/null

if [[ -n "$DOMAIN" ]]; then
  sed "s|__DOMAIN__|$DOMAIN|g" "$INSTALL_DIR/deploy/Caddyfile.production" > /etc/caddy/Caddyfile
  DOMAIN_IP=$(dig +short "$DOMAIN" @1.1.1.1 2>/dev/null | tail -1)
  SERVER_IP=$(curl -fs4 ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')
  if [[ -z "$DOMAIN_IP" ]]; then
    warn "DNS for $DOMAIN not resolvable yet — Caddy will retry certificate issuance automatically."
    warn "Point an A record:  $DOMAIN  →  $SERVER_IP   (see DEPLOYMENT_GUIDE.md)"
  elif [[ "$DOMAIN_IP" != "$SERVER_IP" ]]; then
    warn "$DOMAIN currently resolves to $DOMAIN_IP but this server is $SERVER_IP — update the A record. Caddy will auto-issue SSL once it matches."
  else
    ok "DNS verified: $DOMAIN → $SERVER_IP"
  fi
else
  printf ':80 {\n\treverse_proxy 127.0.0.1:%s\n}\n' "$APP_PORT" > /etc/caddy/Caddyfile
  ok "Caddy serving :80 → app (no-domain mode)"
fi
systemctl enable caddy >/dev/null 2>&1
systemctl reload caddy 2>/dev/null || systemctl restart caddy
ok "Caddy reverse proxy active"

# ----------------------------- 8. health check ------------------------------
step "8/8 Health check"
HEALTH_OK=0
for i in $(seq 1 30); do
  CODE=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$APP_PORT/" || true)
  [[ "$CODE" == "200" ]] && HEALTH_OK=1 && break
  sleep 2
done
[[ $HEALTH_OK -eq 1 ]] && ok "App responding on port $APP_PORT (HTTP 200)" \
                       || warn "App not responding yet — check: journalctl -u ${APP_NAME} -f"

PUBLIC_IP=$(curl -fs4 ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')
echo ""
echo -e "${GREEN}${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo -e "${GREEN}${BOLD}  ✔ Tau ERP deployed successfully${NC}"
echo -e "${GREEN}${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
if [[ -n "$DOMAIN" ]]; then
  echo -e "  ${BOLD}URL:${NC}  https://$DOMAIN   (SSL active once DNS resolves here)"
fi
echo -e "  ${BOLD}URL:${NC}  http://$PUBLIC_IP"
echo -e "  ${BOLD}Logs:${NC}   journalctl -u ${APP_NAME} -f"
echo -e "  ${BOLD}Restart:${NC} systemctl restart ${APP_NAME}"
echo -e "  ${BOLD}Update app later:${NC}  bash deploy/update.sh"
echo -e "  ${BOLD}Backup DB nightly:${NC} see DEPLOYMENT_GUIDE.md § Backups"
echo -e "${GREEN}${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
