/**
 * Tau ERP — D1 seed exporter
 * --------------------------
 * Dumps the local seeded SQLite database (db/custom.db) to a .sql file that
 * can be imported into Cloudflare D1:
 *
 *   bun run db:d1:dump
 *   npx wrangler d1 execute tau-erp --remote --file=d1-seed.sql
 *
 * Uses bun:sqlite (no external sqlite3 binary needed).
 */
import { Database } from "bun:sqlite";
import { writeFileSync } from "node:fs";

const DB_PATH = process.env.DB_PATH ?? "db/custom.db";
const OUT = process.env.OUT ?? "d1-seed.sql";

type MasterRow = { name: string; sql: string; type: string };

const db = new Database(DB_PATH, { readonly: true });

const master = db
  .prepare(
    "SELECT name, sql, type FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type DESC, name"
  )
  .all() as MasterRow[];

const tables = master.filter((m) => m.type === "table");
const others = master.filter((m) => m.type !== "table"); // indexes, views, triggers

const esc = (v: unknown): string => {
  if (v === null) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "bigint") return v.toString();
  if (v instanceof Uint8Array)
    return `X'${Buffer.from(v).toString("hex")}'`;
  const s = String(v).replace(/'/g, "''");
  return `'${s}'`;
};

const lines: string[] = [
  "-- Tau ERP — D1 seed dump (generated by scripts/export-d1-dump.ts)",
  `-- source: ${DB_PATH}`,
  "PRAGMA defer_foreign_keys = true;",
  "BEGIN TRANSACTION;",
];

for (const t of tables) lines.push(`${t.sql.replace(/;\s*$/, "")};`);

for (const t of tables) {
  const rows = db.prepare(`SELECT * FROM "${t.name}"`).all() as Record<string, unknown>[];
  if (rows.length === 0) continue;
  const cols = Object.keys(rows[0]).map((c) => `"${c}"`).join(", ");
  for (const row of rows) {
    const vals = Object.values(row).map(esc).join(", ");
    lines.push(`INSERT INTO "${t.name}" (${cols}) VALUES (${vals});`);
  }
  console.log(`  ${t.name}: ${rows.length} rows`);
}

for (const o of others) lines.push(`${o.sql.replace(/;\s*$/, "")};`);

lines.push("COMMIT;");
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`✔ wrote ${OUT} (${tables.length} tables) — import with:`);
console.log(`  npx wrangler d1 execute tau-erp --remote --file=${OUT}`);
